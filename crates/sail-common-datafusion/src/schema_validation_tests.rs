use std::sync::Arc;

use datafusion::arrow::datatypes::Field;

use super::*;

type TestResult = Result<()>;
fn fields(names: &[&str]) -> Vec<FieldRef> {
    names
        .iter()
        .map(|name| Arc::new(Field::new(*name, DataType::Int32, true)))
        .collect()
}
fn nested(ty: DataType) -> Vec<FieldRef> {
    vec![Arc::new(Field::new("outer", ty, true))]
}
fn assert_error(
    fields: &[FieldRef],
    sensitive: bool,
    condition: &str,
    parameter: &str,
) -> TestResult {
    let result = validate_field_names(fields, sensitive);
    let Err(DataFusionError::External(error)) = result else {
        return datafusion_common::internal_err!(
            "expected structured duplicate error, got {result:?}"
        );
    };
    let error = error
        .downcast_ref::<StructuredSparkError>()
        .ok_or_else(|| {
            datafusion_common::internal_datafusion_err!("lost structured duplicate error")
        })?;
    assert_eq!(error.class, "org.apache.spark.sql.AnalysisException");
    assert_eq!(error.condition, condition);
    let invalid = condition == "INVALID_ATTRIBUTE_NAME_SYNTAX";
    assert_eq!(error.sql_state, if invalid { "42601" } else { "42711" });
    assert_eq!(
        error.parameters,
        HashMap::from([(
            if invalid { "name" } else { "columnName" }.into(),
            parameter.into()
        )])
    );
    Ok(())
}

#[test]
fn duplicate_checks_match_actual_spark_421_schemautils() -> TestResult {
    // Exact cases from the independent JVM oracle, not generated by this validator.
    let mixed = DataType::Struct(fields(&["Foo", "foo"]).into());
    assert_error(
        &fields(&["Foo", "foo"]),
        false,
        "COLUMN_ALREADY_EXISTS",
        "`foo`",
    )?;
    validate_field_names(&fields(&["Foo", "foo"]), true)?;
    assert_error(
        &nested(mixed.clone()),
        false,
        "COLUMN_ALREADY_EXISTS",
        "`foo`",
    )?;
    assert_error(
        &nested(DataType::List(Arc::new(Field::new(
            "element",
            mixed.clone(),
            true,
        )))),
        false,
        "COLUMN_ALREADY_EXISTS",
        "`foo`",
    )?;
    let map = DataType::Map(
        Arc::new(Field::new(
            "entries",
            DataType::Struct(
                vec![
                    Field::new("key", DataType::Utf8, false),
                    Field::new("value", mixed.clone(), true),
                ]
                .into(),
            ),
            false,
        )),
        false,
    );
    assert_error(&nested(map), false, "COLUMN_ALREADY_EXISTS", "`foo`")?;
    let mut parent = nested(mixed);
    parent.extend(fields(&["Z", "z"]));
    assert_error(&parent, false, "COLUMN_ALREADY_EXISTS", "`z`")?;
    for (names, sensitive, condition, expected) in [
        (
            vec!["Z", "z", "A", "a"],
            false,
            "COLUMN_ALREADY_EXISTS",
            "`a`",
        ),
        (
            vec!["İ", "i\u{307}"],
            false,
            "COLUMN_ALREADY_EXISTS",
            "`i\u{307}`",
        ),
        (
            vec!["A.B", "a.b"],
            false,
            "COLUMN_ALREADY_EXISTS",
            "`a`.`b`",
        ),
        (
            vec!["A`B", "a`b"],
            false,
            "INVALID_ATTRIBUTE_NAME_SYNTAX",
            "a`b",
        ),
        (
            vec!["\u{e000}", "\u{e000}", "𐀀", "𐀀"],
            true,
            "COLUMN_ALREADY_EXISTS",
            "`𐀀`",
        ),
        (vec!["Foo", "Foo"], true, "COLUMN_ALREADY_EXISTS", "`Foo`"),
    ] {
        assert_error(&fields(&names), sensitive, condition, expected)?;
    }
    Ok(())
}

#[test]
fn arrow_array_layouts_retain_recursive_validation() -> TestResult {
    let element = Arc::new(Field::new(
        "element",
        DataType::Struct(fields(&["Foo", "foo"]).into()),
        true,
    ));
    for ty in [
        DataType::List(element.clone()),
        DataType::LargeList(element.clone()),
        DataType::FixedSizeList(element, 2),
    ] {
        let fields = nested(ty);
        assert_error(&fields, false, "COLUMN_ALREADY_EXISTS", "`foo`")?;
        validate_field_names(&fields, true)?;
    }
    Ok(())
}

#[test]
fn diagnostic_identifier_formatting_preserves_spark_attribute_syntax() -> TestResult {
    for (name, expected) in [
        ("", "``"),
        ("``", "``"),
        ("`a.b`", "`a.b`"),
        ("`a``b`", "`a``b`"),
        ("x.`a.b`", "`x`.`a.b`"),
        ("__auto_generated_subquery_name.x", "`x`"),
    ] {
        assert_eq!(quote_sql_identifier(name)?, expected);
    }
    for name in [".a", "a.", "a..b", "a`b", "`a`b", "`a"] {
        assert!(quote_sql_identifier(name).is_err(), "{name}");
    }
    Ok(())
}
